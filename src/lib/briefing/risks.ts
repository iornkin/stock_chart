import type { InstrumentConfig } from "@/config/instruments";

export function generalRisks(inst: InstrumentConfig): string[] {
  if (inst.kind === "stock") {
    return [
      "실적 위험: 분기 실적·가이던스가 시장 기대와 다르면 주가가 크게 움직일 수 있습니다.",
      "밸류에이션 위험: 높은 이익 배수(PER 등)로 거래되는 종목은 성장 기대가 낮아질 때 가격 조정 폭이 커질 수 있습니다.",
      "사업·규제 위험: 경쟁 심화, 규제·소송, 공급망, 주요 고객·제품 의존도 변화가 실적에 영향을 줄 수 있습니다.",
      "지수 영향: 대형 기술주는 Nasdaq-100·S&P 500 비중이 커서 지수 전반의 위험 선호 변화와 함께 움직이는 경향이 있습니다.",
    ];
  }
  switch (inst.strategy) {
    case "leveraged":
      return [
        `일일 목표 구조: 이 ETF 는 기초지수 '하루' 수익률의 ${inst.leverage ?? "n"}배를 목표로 하며, 하루를 넘는 기간의 수익률은 기초지수 수익률 × ${inst.leverage ?? "n"}와 크게 다를 수 있습니다.`,
        "변동성·복리 효과: 기초지수가 오르내림을 반복하는 횡보·고변동 구간에서는 지수가 제자리여도 레버리지 ETF 가격은 하락할 수 있습니다(변동성 손실).",
        "손실 확대: 기초지수 하락 시 손실도 배수로 커지며, 큰 폭의 하락이 이어지면 원금의 상당 부분을 잃을 수 있습니다.",
        "비용: 총보수와 스왑·선물 등 파생상품 운용 비용, 금리 수준에 따른 차입 비용이 장기 성과를 낮출 수 있습니다.",
      ];
    case "covered_call_index":
    case "option_income_active":
      return [
        "상승 참여 제한: 콜옵션을 매도하는 구조이므로 기초지수가 크게 오를 때 상승분의 일부 또는 상당 부분을 얻지 못할 수 있습니다.",
        "하락 위험은 대부분 유지: 옵션 프리미엄은 하락을 일부 완충할 뿐이며, 주식 하락 위험은 상당 부분 그대로 남습니다.",
        "분배금 변동: 분배금은 옵션 프리미엄(시장 변동성), 보유 주식 배당 등에 따라 매달 달라지며 감소할 수 있습니다. 일부 분배금은 자본환급(ROC)으로 분류될 수 있습니다.",
        "높은 분배율 ≠ 높은 총수익: 분배금이 많아도 주가(NAV)가 하락하면 총수익률은 낮거나 마이너스일 수 있습니다. 분배금은 일반 기업의 배당금과 성격이 다릅니다.",
      ];
    case "dividend":
      return [
        "배당 성장의 지속성: 과거의 배당 성장 기록이 앞으로의 배당 증가를 보장하지 않으며, 구성 기업 실적 악화 시 배당이 줄어들 수 있습니다.",
        "구성 종목·업종 위험: 지수 규칙에 따라 특정 업종(금융, 필수소비재, 에너지 등)에 비중이 쏠릴 수 있습니다.",
        "금리 민감도: 고배당·배당성장주는 금리 변화에 따라 상대적 매력이 달라져 가격이 영향을 받을 수 있습니다.",
        "성장주 대비 성과 차이: 기술주 주도 상승장에서는 시장 지수 대비 성과가 뒤처질 수 있습니다.",
      ];
    case "physical_gold":
      return [
        "금 가격 위험: 기업 실적이 아니라 금 가격이 가격을 결정하며, 금 가격은 실질금리·달러 가치·안전자산 수요·중앙은행 매입 등에 영향을 받습니다.",
        "현금흐름 없음: 실물 금은 이자나 배당을 만들지 않으므로 이 ETF 는 일반적으로 분배금이 없습니다.",
        "비용·구조: 신탁 보관 비용(총보수)이 매일 차감되어 장기적으로 금 가격 대비 소폭 낮은 성과가 누적됩니다.",
        "추종 오차: ETF 가격은 금 현물·선물 가격과 장중 시차 및 프리미엄/디스카운트 차이가 있을 수 있습니다.",
      ];
    case "sector":
      return [
        "업종 집중: 특정 업종(반도체·기술)에 집중 투자하므로 업종 사이클과 수요 변화에 따른 변동성이 시장 전체보다 큽니다.",
        "상위 종목 집중: 상위 몇 개 종목의 비중이 높아 해당 기업 실적·뉴스의 영향이 큽니다.",
        "밸류에이션·정책 위험: 수출 규제, 관세, 설비투자 사이클 등 정책·산업 요인에 민감할 수 있습니다.",
      ];
    case "index":
    default:
      return [
        "시장 전체 하락 위험: 지수 ETF 는 개별 기업 위험은 분산되지만 시장 전반의 하락은 피할 수 없습니다.",
        "상위 종목 집중: 시가총액 가중 지수는 대형 기술주 비중이 높아 일부 종목의 움직임이 지수 전체에 큰 영향을 줍니다.",
        "금리·경기 민감도: 금리, 물가, 경기 지표 변화에 따라 지수 전반의 밸류에이션이 바뀔 수 있습니다.",
      ];
  }
}
